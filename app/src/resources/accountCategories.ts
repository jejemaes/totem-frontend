/**
 * /api/v1/accounting/categories/ -- the labels a movement can be filed under.
 *
 * A category is either GENERAL (no account: usable on every account's
 * movements) or OWNED by one account (usable on that account's movements
 * only). The backend enforces that pairing on the movement; `applicable_to` is
 * the filter that lists exactly the categories it would accept, so a dropdown
 * built on it cannot offer a choice that ends in a 422.
 *
 * The owner is set at creation and never moves: the update schema has no
 * `account` key at all.
 */

import { apiDelete, apiFetch, patchJson, postJson } from '@/api/client'
import {
  fetchAllPages,
  fetchDisplayNames,
  fetchList,
  type ListQuery,
  type Page,
} from '@/api/list'
import type { RelationFetch } from '@/components/form/fields/many2one'

import type { AccountRef } from './accounts'

/**
 * A category as the backend nests it in a movement. `color` is a palette
 * INDEX 0..15, see `@/components/colors`.
 *
 * A `type` and not an `interface`: only type aliases get the implicit index
 * signature that makes them assignable to `RelationRecord`.
 */
export type AccountCategoryRef = {
  /** A ULID, generated by the backend. */
  id: string
  name: string
  color: number
}

/** One row of the list. */
export type AccountCategoryRow = AccountCategoryRef & {
  /** `null` for a general category. */
  account: AccountRef | null
}

/**
 * List responses are serialised with `exclude_unset=True`, so ONLY the keys
 * asked for in `?fields=` come back. `satisfies` makes a typo here a compile
 * error rather than a silently missing column.
 */
export const ACCOUNT_CATEGORY_LIST_FIELDS = [
  'id',
  'name',
  'color',
  'account',
] as const satisfies readonly (keyof AccountCategoryRow)[]

/** Fields the backend accepts in `?ordering=`. Anything else is a 422. */
export const ACCOUNT_CATEGORY_SORTABLE = ['name', 'color'] as const

/**
 * A `type` and not an `interface`: only type aliases get the implicit index
 * signature that makes them assignable to `ListFilters`.
 */
export type AccountCategoryFilters = {
  /** Matches the name, case-insensitive. */
  search?: string
  /** The id of the OWNING account: general categories are left out. */
  account?: string
  /** The id of an account: the general categories AND that account's own. */
  applicable_to?: string
}

export function listAccountCategories(
  query: ListQuery<AccountCategoryFilters>,
  signal?: AbortSignal,
): Promise<Page<AccountCategoryRow>> {
  return fetchList<AccountCategoryRow>(
    '/accounting/categories/',
    query,
    ACCOUNT_CATEGORY_LIST_FIELDS,
    signal,
  )
}

export const ACCOUNT_CATEGORY_RELATION_FIELDS = [
  'id',
  'name',
  'color',
] as const satisfies readonly (keyof AccountCategoryRef)[]

/**
 * The category dropdown of ONE account's movements: a `RelationFetch` bound to
 * that account.
 *
 * A factory rather than a loader taking the account as an argument, because
 * the widget only ever passes a search term and a signal. `applicable_to` and
 * not `account`: the latter would hide the general categories, which are the
 * ones most movements use.
 *
 * `color` is asked for so the dots and the chips are painted without a second
 * request.
 */
export function searchApplicableCategories(accountId: string): RelationFetch {
  return (search, signal) =>
    fetchAllPages<AccountCategoryRef>(
      '/accounting/categories/',
      ACCOUNT_CATEGORY_RELATION_FIELDS,
      { filters: { search, applicable_to: accountId } },
      signal,
    )
}

/**
 * The labels of a few known account categories: `RelationResolve` shaped, for a filter
 * that holds an id and nothing to label it with.
 *
 * `id`, `name` and `color`: the dot is painted too.
 */
export function accountCategoryDisplayNames(
  ids: string[],
  signal?: AbortSignal,
): Promise<AccountCategoryRef[]> {
  return fetchDisplayNames<AccountCategoryRef>('/accounting/categories/', ids, signal)
}

/** The model has nothing the list row does not show. */
export type AccountCategoryDetail = AccountCategoryRow

export function fetchAccountCategory(
  id: string,
  signal?: AbortSignal,
): Promise<AccountCategoryDetail> {
  return apiFetch<AccountCategoryDetail>(`/accounting/categories/${encodeURIComponent(id)}/`, {
    signal,
  })
}

export interface AccountCategoryCreatePayload {
  /** Unique among the general categories, or among one account's own. */
  name: string
  /** Defaults to 0, the first palette entry. */
  color?: number
  /** An id; `null` or omitted for a general category. Fixed for good once created. */
  account?: string | null
}

export function createAccountCategory(
  payload: AccountCategoryCreatePayload,
): Promise<AccountCategoryDetail> {
  return postJson<AccountCategoryDetail>('/accounting/categories/', payload)
}

/**
 * A PATCH body, and only the edited keys. Written out rather than
 * `Partial<AccountCategoryCreatePayload>`: the update schema has no `account`,
 * and a type that allowed one would let a moved owner LOOK saved while the
 * backend silently ignored it.
 */
export type AccountCategoryUpdatePayload = {
  name?: string
  color?: number
}

export function updateAccountCategory(
  id: string,
  payload: AccountCategoryUpdatePayload,
): Promise<AccountCategoryDetail> {
  return patchJson<AccountCategoryDetail>(
    `/accounting/categories/${encodeURIComponent(id)}/`,
    payload,
  )
}

/** The movements filed under it keep existing: their FK is `on_delete=SET_NULL`. */
export function deleteAccountCategory(id: string): Promise<void> {
  return apiDelete(`/accounting/categories/${encodeURIComponent(id)}/`)
}
