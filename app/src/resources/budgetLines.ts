/**
 * /api/v1/accounting/budget/{budget_id}/lines/ -- the planned amounts a
 * position is made of.
 *
 * Nested under the BUDGET, not under the position: the position is a field of
 * the line (and a filter of the list), so the screens scope a sub-list to one
 * position with `?position=`. The backend refuses a position belonging to
 * another budget with a field error.
 *
 * Same scopes as the budget itself (`totem.budget.*`). A line's
 * `planned_amount` feeds the stored `total_planned` of its position and the
 * budget's `total_planned_amount`, so any write here makes both stale.
 */

import { apiDelete, apiFetch, patchJson, postJson } from '@/api/client'
import { fetchList, type ListQuery, type Page } from '@/api/list'

import type { Amount } from './accounts'
import type { BudgetPositionRef } from './budgetPositions'
import type { BudgetRef } from './budgets'

function linesPath(budgetId: string): string {
  return `/accounting/budget/${encodeURIComponent(budgetId)}/lines/`
}

/** One row of the list. */
export type BudgetLineRow = {
  /** A ULID, generated by the backend. */
  id: string
  name: string
  sequence: number
  /** A decimal, sent as a string. Read it through toNumberOrNull. */
  planned_amount: Amount
}

/**
 * List responses are serialised with `exclude_unset=True`, so ONLY the keys
 * asked for in `?fields=` come back. The position is not asked for: a sub-list
 * is already scoped to one.
 */
export const BUDGET_LINE_LIST_FIELDS = [
  'id',
  'name',
  'sequence',
  'planned_amount',
] as const satisfies readonly (keyof BudgetLineRow)[]

/** Fields the backend accepts in `?ordering=`. */
export const BUDGET_LINE_SORTABLE = ['sequence', 'name', 'planned_amount'] as const

/** A `type`, for the implicit index signature `ListFilters` needs. */
export type BudgetLineFilters = {
  /** Matches the name, case-insensitive. */
  name?: string
  /** The id of the position. */
  position?: string
}

export function listBudgetLines(
  budgetId: string,
  query: ListQuery<BudgetLineFilters>,
  signal?: AbortSignal,
): Promise<Page<BudgetLineRow>> {
  return fetchList<BudgetLineRow>(linesPath(budgetId), query, BUDGET_LINE_LIST_FIELDS, signal)
}

/** What GET .../lines/{id}/ returns. */
export type BudgetLineDetail = BudgetLineRow & {
  budget: BudgetRef
  position: BudgetPositionRef
}

export function fetchBudgetLine(
  budgetId: string,
  id: string,
  signal?: AbortSignal,
): Promise<BudgetLineDetail> {
  return apiFetch<BudgetLineDetail>(`${linesPath(budgetId)}${encodeURIComponent(id)}/`, {
    signal,
  })
}

export interface BudgetLineCreatePayload {
  name: string
  /** An id: a position of THIS budget. */
  position: string
  /** Two decimals at most. */
  planned_amount: number
  /** Defaults to 10 server-side. */
  sequence?: number
}

export function createBudgetLine(
  budgetId: string,
  payload: BudgetLineCreatePayload,
): Promise<BudgetLineDetail> {
  return postJson<BudgetLineDetail>(linesPath(budgetId), payload)
}

/**
 * A PATCH body, and only the edited keys. The update schema takes every create
 * key, `position` included -- a line CAN move to another position of the same
 * budget, even though no screen offers it yet.
 */
export type BudgetLineUpdatePayload = Partial<BudgetLineCreatePayload>

export function updateBudgetLine(
  budgetId: string,
  id: string,
  payload: BudgetLineUpdatePayload,
): Promise<BudgetLineDetail> {
  return patchJson<BudgetLineDetail>(`${linesPath(budgetId)}${encodeURIComponent(id)}/`, payload)
}

export function deleteBudgetLine(budgetId: string, id: string): Promise<void> {
  return apiDelete(`${linesPath(budgetId)}${encodeURIComponent(id)}/`)
}

/**
 * `POST .../lines/resequence/`: numbers the lines 1..n in the order of `ids`.
 *
 * Send EVERY line of the position, in its new order: the backend numbers only
 * the ids it is given and leaves the others alone, so a partial list collides
 * with the sequences it skipped. All or nothing -- one id repeated, unknown or
 * of another budget, and nothing is written (a 422 on `ids`). Needs
 * `totem.budget.update`. Answers 201 with an empty body.
 */
export function resequenceBudgetLines(budgetId: string, ids: string[]): Promise<void> {
  return postJson<void>(`${linesPath(budgetId)}resequence/`, ids)
}
