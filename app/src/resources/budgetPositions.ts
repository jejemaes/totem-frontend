/**
 * /api/v1/accounting/budget/{budget_id}/positions/ -- the share of a budget
 * planned for one category.
 *
 * NESTED under its budget: every call takes the budget id first, and the
 * backend files a creation under the budget of the path. Two server-side rules
 * shape the screens built on this:
 *
 *  - one position per category per budget (a unique constraint, reported as a
 *    field error on `category`);
 *  - the category must be general or belong to the budget's own account -- the
 *    movements' rule, since no other category could ever read a practical
 *    amount. `searchApplicableCategories(accountId)` lists exactly those.
 *
 * There is no scope of its own: the controller reuses the budget's
 * `totem.budget.*` map, so a position is created with `totem.budget.create`
 * and so on. `name` and `color` are copied from the category, read-only.
 */

import { apiDelete, apiFetch, patchJson, postJson } from '@/api/client'
import { fetchAllPages } from '@/api/list'

import type { AccountCategoryRef } from './accountCategories'
import type { Amount } from './accounts'
import type { BudgetRef } from './budgets'

function positionsPath(budgetId: string): string {
  return `/accounting/budget/${encodeURIComponent(budgetId)}/positions/`
}

/**
 * A position as the backend nests it in a line.
 *
 * A `type` and not an `interface`: only type aliases get the implicit index
 * signature that makes them assignable to `RelationRecord`.
 */
export type BudgetPositionRef = {
  id: string
  name: string
  color: number
}

/**
 * A position as the backend reads it -- the base the balance row and the
 * detail are cut from.
 */
export type BudgetPositionRow = {
  /** A ULID, generated by the backend. */
  id: string
  sequence: number
  /** The category's name, copied. Read-only. */
  name: string
  /** The category's palette index, copied. Read-only. */
  color: number
  category: AccountCategoryRef
  /** Sum of the position's lines. Computed, read-only. */
  total_planned: Amount
}

/**
 * One row of the balance: what was planned for a category against what was
 * actually booked on it.
 *
 * `category` is carried for its id: the practical amount's pencil opens the
 * account's movements filtered on it, which is the list that amount sums.
 */
export type BudgetBalanceRow = Pick<
  BudgetPositionRow,
  'id' | 'sequence' | 'name' | 'color' | 'category' | 'total_planned'
> & {
  /** Sum of the category's movements on the budget's account. Computed, read-only. */
  total_practical: Amount
}

export const BUDGET_POSITION_BALANCE_FIELDS = [
  'id',
  'sequence',
  'name',
  'color',
  'category',
  'total_planned',
  'total_practical',
] as const satisfies readonly (keyof BudgetBalanceRow)[]

/**
 * EVERY position of a budget, in sequence order, with both totals.
 *
 * All pages rather than one: the balance shows a total under its table, and a
 * total under a paged table would silently describe the visible page only. A
 * budget holds a handful of categories, so this is one request in practice.
 */
export function listBudgetBalance(
  budgetId: string,
  signal?: AbortSignal,
): Promise<BudgetBalanceRow[]> {
  return fetchAllPages<BudgetBalanceRow>(
    positionsPath(budgetId),
    BUDGET_POSITION_BALANCE_FIELDS,
    { ordering: 'sequence' },
    signal,
  )
}

/** What GET .../positions/{id}/ returns. */
export type BudgetPositionDetail = BudgetPositionRow & {
  budget: BudgetRef
}

export function fetchBudgetPosition(
  budgetId: string,
  id: string,
  signal?: AbortSignal,
): Promise<BudgetPositionDetail> {
  return apiFetch<BudgetPositionDetail>(`${positionsPath(budgetId)}${encodeURIComponent(id)}/`, {
    signal,
  })
}

export interface BudgetPositionCreatePayload {
  /** An id: general, or owned by the budget's account. */
  category: string
  /** Defaults to 10 server-side. */
  sequence?: number
}

export function createBudgetPosition(
  budgetId: string,
  payload: BudgetPositionCreatePayload,
): Promise<BudgetPositionDetail> {
  return postJson<BudgetPositionDetail>(positionsPath(budgetId), payload)
}

/** A PATCH body, and only the edited keys. Both keys are accepted on update. */
export type BudgetPositionUpdatePayload = Partial<BudgetPositionCreatePayload>

export function updateBudgetPosition(
  budgetId: string,
  id: string,
  payload: BudgetPositionUpdatePayload,
): Promise<BudgetPositionDetail> {
  return patchJson<BudgetPositionDetail>(
    `${positionsPath(budgetId)}${encodeURIComponent(id)}/`,
    payload,
  )
}

/** Its lines go with it: `BudgetLine.position` is `on_delete=CASCADE`. */
export function deleteBudgetPosition(budgetId: string, id: string): Promise<void> {
  return apiDelete(`${positionsPath(budgetId)}${encodeURIComponent(id)}/`)
}
