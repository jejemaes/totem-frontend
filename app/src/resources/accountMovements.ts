/**
 * /api/v1/accounting/movements/ -- the entries booked on an account.
 *
 * One signed `amount` carries the direction: negative is a debit (an expense),
 * positive a credit (a revenue), and zero is refused by a check constraint.
 * There is no separate direction column to keep in step, which is why the form
 * takes the amount as typed.
 *
 * A movement belongs to its account for good: `account` is in the create
 * schema only. The screens therefore always reach movements THROUGH an
 * account, and the list is scoped by the `account` filter.
 */

import { apiDelete, apiFetch, patchJson, postJson } from '@/api/client'
import { fetchGroups, type GroupPage, type GroupQuery } from '@/api/groupBy'
import { fetchList, type ListQuery, type Page } from '@/api/list'

import type { AccountCategoryRef } from './accountCategories'
import type { AccountRef, Amount } from './accounts'

/** One row of the list. Relations are read as nested objects and written as ids. */
export type AccountMovementRow = {
  /** A ULID, generated by the backend. */
  id: string
  name: string
  /** A calendar day, `YYYY-MM-DD`: no time, no timezone. */
  date: string
  amount: Amount
  category: AccountCategoryRef | null
}

/**
 * List responses are serialised with `exclude_unset=True`, so ONLY the keys
 * asked for in `?fields=` come back. `satisfies` makes a typo here a compile
 * error rather than a silently missing column.
 */
export const ACCOUNT_MOVEMENT_LIST_FIELDS = [
  'id',
  'name',
  'date',
  'amount',
  'category',
] as const satisfies readonly (keyof AccountMovementRow)[]

/** Fields the backend accepts in `?ordering=`. A relation is not one of them. */
export const ACCOUNT_MOVEMENT_SORTABLE = ['date', 'amount', 'name', 'reference'] as const

export type MovementDirection = 'debit' | 'credit'

/**
 * A `type` and not an `interface`: only type aliases get the implicit index
 * signature that makes them assignable to `ListFilters`.
 */
export type AccountMovementFilters = {
  /** Matches the name OR the reference, case-insensitive. */
  search?: string
  account?: string
  category?: string
  /** Inclusive bounds, both calendar days `YYYY-MM-DD`. */
  date_from?: string
  date_to?: string
  /** `debit` keeps the negative amounts, `credit` the positive ones. */
  direction?: MovementDirection
}

export function listAccountMovements(
  query: ListQuery<AccountMovementFilters>,
  signal?: AbortSignal,
): Promise<Page<AccountMovementRow>> {
  return fetchList<AccountMovementRow>(
    '/accounting/movements/',
    query,
    ACCOUNT_MOVEMENT_LIST_FIELDS,
    signal,
  )
}

/**
 * What `POST /accounting/movements/group-by/` groups by, as the service
 * declares them (`AccountMovementService.group_by_dimensions`). `account` and
 * `category` come back nested as the list renders them; a `date_*` is the
 * first day of its period, `YYYY-MM-DD`.
 */
export const ACCOUNT_MOVEMENT_DIMENSIONS = [
  'account',
  'category',
  'date_day',
  'date_week',
  'date_month',
  'date_quarter',
  'date_year',
] as const

/**
 * Its measures. Sums are decimal STRINGS (`"-40.00"`), `amount_avg` and
 * `amount_share` are floats, `count` an integer -- and any of them null over a
 * group with nothing to aggregate (`credit_sum` of a month of expenses).
 * `amount_share` is the share of each category in its period, 0-100.
 */
export const ACCOUNT_MOVEMENT_MEASURES = [
  'count',
  'amount_sum',
  'amount_avg',
  'amount_min',
  'amount_max',
  'debit_sum',
  'credit_sum',
  'amount_share',
] as const

export type AccountMovementDimension = (typeof ACCOUNT_MOVEMENT_DIMENSIONS)[number]
export type AccountMovementMeasure = (typeof ACCOUNT_MOVEMENT_MEASURES)[number]

/** The same filters as the list: the backend takes its `list_filter_schema`. */
export function groupAccountMovements(
  query: GroupQuery<AccountMovementFilters>,
  signal?: AbortSignal,
): Promise<GroupPage> {
  return fetchGroups('/accounting/movements/group-by/', query, signal)
}

/** What GET /accounting/movements/{id}/ returns. */
export type AccountMovementDetail = AccountMovementRow & {
  account: AccountRef
  description: string | null
  /** An invoice or order number. */
  reference: string | null
  create_date: string
  update_date: string
}

export function fetchAccountMovement(
  id: string,
  signal?: AbortSignal,
): Promise<AccountMovementDetail> {
  return apiFetch<AccountMovementDetail>(`/accounting/movements/${encodeURIComponent(id)}/`, {
    signal,
  })
}

export interface AccountMovementCreatePayload {
  /** An id. Fixed for good: the update schema does not take it. */
  account: string
  /** Signed, never zero. Two decimals at most. */
  amount: number
  name: string
  /** `YYYY-MM-DD`. */
  date: string
  description?: string | null
  reference?: string | null
  /**
   * An id, or `null`. It must be applicable to the account -- general, or
   * owned by it -- or the backend answers a 422 on `category`.
   */
  category?: string | null
}

export function createAccountMovement(
  payload: AccountMovementCreatePayload,
): Promise<AccountMovementDetail> {
  return postJson<AccountMovementDetail>('/accounting/movements/', payload)
}

/**
 * A PATCH body, and only the edited keys. `Omit`, not a bare `Partial`: the
 * update schema has no `account`, and a type allowing one would let a moved
 * movement LOOK saved while the backend ignored the key.
 */
export type AccountMovementUpdatePayload = Partial<Omit<AccountMovementCreatePayload, 'account'>>

export function updateAccountMovement(
  id: string,
  payload: AccountMovementUpdatePayload,
): Promise<AccountMovementDetail> {
  return patchJson<AccountMovementDetail>(
    `/accounting/movements/${encodeURIComponent(id)}/`,
    payload,
  )
}

export function deleteAccountMovement(id: string): Promise<void> {
  return apiDelete(`/accounting/movements/${encodeURIComponent(id)}/`)
}
