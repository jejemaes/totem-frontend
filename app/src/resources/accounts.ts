/**
 * /api/v1/accounting/accounts/ -- the ledgers movements are booked on.
 *
 * A full CRUD resource, each verb behind its own `totem.account.*` scope. The
 * three totals are computed by the backend from the movements, so they are
 * read-only: neither schema accepts them on write.
 */

import { apiDelete, apiFetch, patchJson, postJson } from '@/api/client'
import {
  fetchAllPages,
  fetchDisplayNames,
  fetchList,
  type ListQuery,
  type Page,
} from '@/api/list'
import type { RelationRecord } from '@/components/form/fields/many2one'
import { toNumberOrNull } from '@/components/form/fields/values'

/**
 * An account as the backend nests it in a movement or a category.
 *
 * A `type` and not an `interface`: only type aliases get the implicit index
 * signature that makes them assignable to `RelationRecord`.
 */
export type AccountRef = {
  /** A ULID, generated by the backend. */
  id: string
  code: string
  name: string
}

/**
 * A decimal, as the backend serialises it: the schema allows a number OR a
 * string, and a Django DecimalField goes out as a string so no digit is lost
 * to a float. Read it through toNumberOrNull, never with a bare arithmetic
 * operator: `"-12.50" < 0` happens to work, `"10.00" + 1` does not.
 */
export type Amount = number | string

/**
 * An amount as a cell shows it: always two decimals, grouped thousands, `—`
 * when there is none.
 *
 * Two decimals FIXED, unlike FloatField's free precision: the column is a
 * money column, and `12.5` next to `3.75` misaligns the digits a reader scans.
 * `locale` defaults to the browser's; the spec pins one.
 */
export function formatAmount(value: Amount | null | undefined, locale?: string): string {
  const parsed = toNumberOrNull(value)
  if (parsed === null) return '—'
  return new Intl.NumberFormat(locale, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(parsed)
}

/**
 * Which side an amount sits on, for colouring: a debit is negative, a credit
 * positive -- the backend's own convention, see the `direction` filter. Zero
 * and unparseable amounts are neither, so they stay uncoloured rather than
 * pretending to be a revenue.
 */
export function amountDirection(value: Amount | null | undefined): 'debit' | 'credit' | null {
  const parsed = toNumberOrNull(value)
  if (parsed === null || parsed === 0) return null
  return parsed < 0 ? 'debit' : 'credit'
}

/**
 * The sum of a column of amounts, exact to the cent.
 *
 * Summed in integer CENTS rather than as floats: `0.1 + 0.2` is
 * 0.30000000000000004, and a total that is off by a hair is a total that
 * `formatAmount` happens to hide until it rounds the wrong way. Two decimals is
 * what every amount of this API carries. An unparseable entry is skipped, not
 * counted as zero -- it is the same thing here, and the honest name for it.
 */
export function sumAmounts(values: readonly (Amount | null | undefined)[]): number {
  let cents = 0
  for (const value of values) {
    const parsed = toNumberOrNull(value)
    if (parsed !== null) cents += Math.round(parsed * 100)
  }
  return cents / 100
}

/** One row of the list. */
export type AccountRow = {
  id: string
  code: string
  name: string
  active: boolean
  /** Sum of every movement. Computed, read-only. */
  balance: Amount
}

/**
 * List responses are serialised with `exclude_unset=True`, so ONLY the keys
 * asked for in `?fields=` come back. `satisfies` makes a typo here a compile
 * error rather than a silently missing column.
 */
export const ACCOUNT_LIST_FIELDS = [
  'id',
  'code',
  'name',
  'active',
  'balance',
] as const satisfies readonly (keyof AccountRow)[]

/**
 * Fields the backend accepts in `?ordering=`. The totals are sortable although
 * they are computed: the queryset annotates them.
 */
export const ACCOUNT_SORTABLE = ['code', 'name', 'active', 'balance'] as const

/**
 * A `type` and not an `interface`: only type aliases get the implicit index
 * signature that makes them assignable to `ListFilters`.
 */
export type AccountFilters = {
  /** Matches the code OR the name, case-insensitive. */
  search?: string
  active?: boolean
}

export function listAccounts(
  query: ListQuery<AccountFilters>,
  signal?: AbortSignal,
): Promise<Page<AccountRow>> {
  return fetchList<AccountRow>('/accounting/accounts/', query, ACCOUNT_LIST_FIELDS, signal)
}

export const ACCOUNT_RELATION_FIELDS = [
  'id',
  'code',
  'name',
] as const satisfies readonly (keyof AccountRef)[]

/**
 * The loader of an account dropdown: `RelationFetch` shaped. `search` matches
 * the code or the name, so typing either finds the account.
 */
export function searchAccounts(
  search: string | null,
  signal?: AbortSignal,
): Promise<AccountRef[]> {
  return fetchAllPages<AccountRef>(
    '/accounting/accounts/',
    ACCOUNT_RELATION_FIELDS,
    { filters: { search } },
    signal,
  )
}

/**
 * The labels of a few known accounts: `RelationResolve` shaped, for a filter
 * that holds an id and nothing to label it with.
 *
 * `id`, `code` and `name`: what displayAccount reads.
 */
export function accountDisplayNames(
  ids: string[],
  signal?: AbortSignal,
): Promise<AccountRef[]> {
  return fetchDisplayNames<AccountRef>('/accounting/accounts/', ids, signal)
}

/**
 * `CODE · Name`: the name alone is ambiguous to an accountant, who thinks in
 * codes, and the code alone is opaque to everyone else. Falls back like
 * displayRelation, so it never returns ''.
 */
export function displayAccount(record: RelationRecord): string {
  const code = typeof record.code === 'string' ? record.code.trim() : ''
  const name = typeof record.name === 'string' ? record.name.trim() : ''
  if (code && name) return `${code} · ${name}`
  return code || name || String(record.id)
}

/** What GET /accounting/accounts/{id}/ returns. */
export type AccountDetail = AccountRow & {
  description: string | null
  /** Sum of the negative movements, as a negative amount. */
  total_debit: Amount
  /** Sum of the positive movements. */
  total_credit: Amount
  create_date: string
  update_date: string
}

export function fetchAccount(id: string, signal?: AbortSignal): Promise<AccountDetail> {
  return apiFetch<AccountDetail>(`/accounting/accounts/${encodeURIComponent(id)}/`, { signal })
}

export interface AccountCreatePayload {
  /** `^[A-Z0-9_-]{1,50}$`: the backend refuses lower case rather than folding it. */
  code: string
  /** Unique: a duplicate comes back as a field error. */
  name: string
  description?: string | null
  /** Defaults to true server-side. */
  active?: boolean
}

export function createAccount(payload: AccountCreatePayload): Promise<AccountDetail> {
  return postJson<AccountDetail>('/accounting/accounts/', payload)
}

/**
 * A PATCH body, and only the edited keys: the backend deserialises with
 * `exclude_unset=True`, so an omitted key is left untouched where an explicit
 * `null` is written.
 */
export type AccountUpdatePayload = Partial<AccountCreatePayload>

export function updateAccount(id: string, payload: AccountUpdatePayload): Promise<AccountDetail> {
  return patchJson<AccountDetail>(`/accounting/accounts/${encodeURIComponent(id)}/`, payload)
}

/**
 * An account holding movements cannot be deleted: `AccountMovement.account` is
 * `on_delete=PROTECT`. The refusal comes back as an ApiError, so the caller
 * must show it rather than assume the row is gone. Its own categories, on the
 * other hand, CASCADE.
 */
export function deleteAccount(id: string): Promise<void> {
  return apiDelete(`/accounting/accounts/${encodeURIComponent(id)}/`)
}
