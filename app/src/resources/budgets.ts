/**
 * /api/v1/accounting/budget/ -- forecasts of an account: what is planned per
 * category, set against what its movements actually amount to.
 *
 * The path segment is SINGULAR on the API, unlike every other collection; the
 * SPA routes say `/accounting/budgets` all the same, so this module is the one
 * place the API's spelling appears.
 *
 * A budget is tied to its account for good: the update schema has no
 * `account`. Its positions and lines are nested endpoints of their own
 * (`/budget/{id}/positions/`, `/budget/{id}/lines/`): see budgetPositions.ts
 * and budgetLines.ts.
 */

import { apiDelete, apiFetch, patchJson, postJson } from '@/api/client'
import { fetchList, type ListQuery, type Page } from '@/api/list'

import type { AccountRef, Amount } from './accounts'
import type { UserRef } from './users'

/**
 * A budget as the backend nests it in a position or a line.
 *
 * A `type` and not an `interface`: only type aliases get the implicit index
 * signature that makes them assignable to `RelationRecord`.
 */
export type BudgetRef = {
  id: string
  name: string
}

/** One row of the list. Relations are read as nested objects and written as ids. */
export type BudgetRow = {
  /** A ULID, generated by the backend. */
  id: string
  name: string
  account: AccountRef
  /** The user in charge. `null` when unassigned, or when that user was deleted. */
  user: UserRef | null
  /** Sum of the positions' planned totals. Computed, read-only. */
  total_planned_amount: Amount
  /** Sum of the positions' actual totals. Computed, read-only. */
  total_practical_amount: Amount
  active: boolean
}

/**
 * List responses are serialised with `exclude_unset=True`, so ONLY the keys
 * asked for in `?fields=` come back. `satisfies` makes a typo here a compile
 * error rather than a silently missing column.
 */
export const BUDGET_LIST_FIELDS = [
  'id',
  'name',
  'account',
  'user',
  'total_planned_amount',
  'total_practical_amount',
  'active',
] as const satisfies readonly (keyof BudgetRow)[]

/**
 * Fields the backend accepts in `?ordering=`. The two totals are stored
 * computed fields, hence sortable; `create_date` is accepted too but no column
 * shows it.
 */
export const BUDGET_SORTABLE = [
  'name',
  'active',
  'total_planned_amount',
  'total_practical_amount',
] as const

/**
 * Filters this endpoint accepts. There is NO `search`: the free-text filter is
 * `name`, which is why the list binds its toolbar box to that key.
 *
 * A `type` and not an `interface`: only type aliases get the implicit index
 * signature that makes them assignable to `ListFilters`.
 */
export type BudgetFilters = {
  /** Matches the name, case-insensitive. */
  name?: string
  /** The id of the account. */
  account?: string
  /** The id (a UUID) of the user in charge. */
  user?: string
  active?: boolean
}

export function listBudgets(
  query: ListQuery<BudgetFilters>,
  signal?: AbortSignal,
): Promise<Page<BudgetRow>> {
  return fetchList<BudgetRow>('/accounting/budget/', query, BUDGET_LIST_FIELDS, signal)
}

/** What GET /accounting/budget/{id}/ returns. */
export type BudgetDetail = BudgetRow & {
  /** HTML, sanitised server-side. `null` when empty. */
  note: string | null
  /**
   * Movements of the account whose category has no position in this budget,
   * uncategorised ones included. Computed on read, never stored.
   */
  uncategorized_movement_count: number
  create_date: string
  update_date: string
}

export function fetchBudget(id: string, signal?: AbortSignal): Promise<BudgetDetail> {
  return apiFetch<BudgetDetail>(`/accounting/budget/${encodeURIComponent(id)}/`, { signal })
}

export interface BudgetCreatePayload {
  name: string
  /** An id. Fixed for good: the update schema does not take it. */
  account: string
  /** A user id (a UUID), or `null` for nobody. */
  user?: string | null
  /** Defaults to true server-side. */
  active?: boolean
  note?: string | null
}

export function createBudget(payload: BudgetCreatePayload): Promise<BudgetDetail> {
  return postJson<BudgetDetail>('/accounting/budget/', payload)
}

/**
 * A PATCH body, and only the edited keys. `Omit`, not a bare `Partial`: the
 * update schema has no `account`, and a type allowing one would let a moved
 * budget LOOK saved while the backend ignored the key.
 */
export type BudgetUpdatePayload = Partial<Omit<BudgetCreatePayload, 'account'>>

export function updateBudget(id: string, payload: BudgetUpdatePayload): Promise<BudgetDetail> {
  return patchJson<BudgetDetail>(`/accounting/budget/${encodeURIComponent(id)}/`, payload)
}

/** Its positions and lines go with it. A refusal comes back as an ApiError. */
export function deleteBudget(id: string): Promise<void> {
  return apiDelete(`/accounting/budget/${encodeURIComponent(id)}/`)
}
